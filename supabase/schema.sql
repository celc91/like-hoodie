create table if not exists public.carts (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null references auth.users(id) on delete cascade,
  status text not null default 'open' check (status in ('open', 'empty', 'converted')),
  step text not null default 'cart' check (step in ('cart', 'checkout')),
  items jsonb not null default '[]'::jsonb check (jsonb_typeof(items) = 'array'),
  item_count integer not null default 0 check (item_count >= 0),
  subtotal integer not null default 0 check (subtotal >= 0),
  currency text not null default 'MXN',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index if not exists carts_user_idx on public.carts (user_id, status);
create index if not exists carts_updated_idx on public.carts (updated_at desc);

drop trigger if exists carts_touch_updated_at on public.carts;
create trigger carts_touch_updated_at
  before update on public.carts
  for each row execute function public.touch_updated_at();

-- ---------------------------------------------------------------------------
-- Pedidos
-- ---------------------------------------------------------------------------

create table if not exists public.orders (
  id uuid primary key default gen_random_uuid(),
  number bigint generated by default as identity (start with 1001) unique,
  user_id uuid references auth.users(id) on delete set null,
  cart_id uuid references public.carts(id) on delete set null,
  status text not null default 'pending'
    check (status in ('pending', 'confirmed', 'production', 'shipped', 'delivered', 'cancelled')),
  customer_name text not null,
  email text not null,
  phone text,
  address text,
  city text,
  zip text,
  notes text,
  items jsonb not null default '[]'::jsonb check (jsonb_typeof(items) = 'array'),
  item_count integer not null default 0 check (item_count >= 0),
  subtotal integer not null default 0 check (subtotal >= 0),
  shipping integer not null default 0 check (shipping >= 0),
  total integer not null default 0 check (total >= 0),
  payment_method text not null default 'demo',
  payment_status text not null default 'demo',
  admin_notes text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index if not exists orders_created_idx on public.orders (created_at desc);
create index if not exists orders_status_idx on public.orders (status);
create index if not exists orders_email_idx on public.orders (email);

drop trigger if exists orders_touch_updated_at on public.orders;
create trigger orders_touch_updated_at
  before update on public.orders
  for each row execute function public.touch_updated_at();

